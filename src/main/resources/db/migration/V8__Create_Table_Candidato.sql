CREATE TABLE candidato(
    can_id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    can_nome VARCHAR(200),
    can_sobrenome VARCHAR(200),
    can_nomesocial VARCHAR(200),
    can_foto VARCHAR(200),
    can_datanascimento DATE,
    can_cpf VARCHAR(15),
    can_cnpj VARCHAR(45),
    can_grauinstrucao VARCHAR(20),
    can_formacao VARCHAR(100),
    can_cor VARCHAR(50),
    can_etnia VARCHAR(150),
    can_ocupacao VARCHAR(200),
    can_nacionalidade VARCHAR(100),
    can_id_vice UUID,
    can_certidao VARCHAR(100),
    can_consulta VARCHAR(200),
    can_ativo BOOLEAN DEFAULT TRUE,
    criadoEm DATE NOT NULL,
    atualizadoEm DATE NOT NULL,
    car_id UUID,
    sit_id UUID,
    par_id UUID,
    est_id UUID,
    enc_id UUID,
    CONSTRAINT fk_candidato_cargo FOREIGN KEY (car_id) REFERENCES cargo(car_id),
    CONSTRAINT fk_candidato_situacao FOREIGN KEY (sit_id) REFERENCES situacao(sit_id),
    CONSTRAINT fk_candidato_partido FOREIGN KEY (par_id) REFERENCES partido(par_id),
    CONSTRAINT fk_candidato_estado FOREIGN KEY (est_id) REFERENCES estado(est_id),
    CONSTRAINT fk_candidato_encarregadodados FOREIGN KEY (enc_id) REFERENCES encarregadodados(enc_id)
);